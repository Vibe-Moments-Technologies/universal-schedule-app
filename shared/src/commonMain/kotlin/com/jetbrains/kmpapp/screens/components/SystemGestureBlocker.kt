package com.jetbrains.kmpapp.screens.components

import androidx.compose.ui.Modifier
import androidx.compose.ui.unit.dp

/**
 * Невидимая зона-блокер системных жестов (только iOS).
 *
 * Проблема: свайп системной шторки снизу перехватывался приложением —
 * расписание «уезжало» вместо открытия шторки. iOS отдаёт жест системе
 * только если верхний слой не заявил о собственном интересе.
 *
 * Решение (репорт владельца): от самого низа экрана до середины дока —
 * невидимый слой, который «потребляет» все касания, чтобы Compose не
 * дёргал контент под ним; свайп система распознаёт по edge-зоне
 * домашнего индикатора. Никаких визуальных изменений: слой не рисует
 * ничего, не перекрывает док (стоит ниже него по z-order) и не
 * сдвигает разметку.
 *
 * На Android — no-op: системные жесты там обрабатываются до приложения,
 * блокер не нужен (и навигационная панель кнопочная у большинства).
 */
expect fun Modifier.systemGestureBlocker(): Modifier

/** Высота блокера: от низа экрана до середины дока. */
internal val GESTURE_BLOCKER_HEIGHT = 44.dp

