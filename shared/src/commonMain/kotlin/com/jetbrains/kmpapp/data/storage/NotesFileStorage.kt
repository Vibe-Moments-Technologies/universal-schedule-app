package com.jetbrains.kmpapp.data.storage

/**
 * Файловый бэкенд заметок к парам и предметам (R2).
 *
 * Заметки — пользовательский контент, а не кеш и не настройка: они
 * обязаны переживать «очистить кеш», «сбросить данные» и любой
 * пересоздатель расписания. PlatformStorage (key-value) для этого
 * не годился: clearAll() сносил всё подряд, а resetAllData хранил
 * заметки в том же контейнере, что и настройки.
 *
 * Реализация платформенная: Android — filesDir, iOS — Documents
 * (папки попадают в системный бэкап). Контракт — строка «файл целиком»:
 * заметок немного, JSON-массив читается и пишется одним куском.
 *
 * Тесты подменяют реализацию: методы открыты для переопределения.
 */
expect open class NotesFileStorage {
    /** Создать бэкенд (пути платформа определяет сама). */
    constructor()

    /** Прочитать файл заметок; null — файла нет/не читается. */
    open fun read(): String?

    /** Записать файл заметок; false — не удалось. */
    open fun write(content: String): Boolean

    /** Удалить файл заметок (полный сброс по явному желанию пользователя). */
    open fun delete(): Boolean
}

