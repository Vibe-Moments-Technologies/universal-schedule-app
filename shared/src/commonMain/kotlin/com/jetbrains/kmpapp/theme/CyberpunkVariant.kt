package com.jetbrains.kmpapp.theme

/**
 * Вариант палитры темы «Киберпанк».
 *
 * Тему перекрасили (маджента → кислотный жёлтый), чтобы она перестала быть
 * похожей на «Кавай», но старая палитра понравилась части пользователей.
 * Решение владельца: сохранить обе и дать выбрать.
 *
 * Это свойство самой темы, а не состояния «включена сейчас»: выбор живёт в
 * хранилище отдельно от [ThemeOverlay], поэтому переключение на Матрицу и
 * обратно его не сбрасывает.
 */
enum class CyberpunkVariant(val displayName: String) {
    /** Текущая палитра: жёлтый + циан + сигнальный красный. */
    NEON("Новая"),

    /** Прежняя палитра: маджента + циан. */
    CLASSIC("Старая");

    companion object {
        /** По умолчанию — новая: она активна у всех, кто тему не настраивал. */
        val DEFAULT: CyberpunkVariant = NEON

        fun fromName(name: String?): CyberpunkVariant =
            entries.firstOrNull { it.name == name } ?: DEFAULT
    }
}
